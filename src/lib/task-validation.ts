import { z } from "zod";

import { isValidLocalDate, isValidLocalTime } from "@/lib/local-time";
import { IMPORTANCE_LEVELS, MAX_ESTIMATED_MINUTES, TASK_STATUSES } from "@/lib/task-rules";

export const TASK_FORM_FIELDS = [
  "title",
  "description",
  "importance",
  "plannedDate",
  "plannedTime",
  "deadlineDate",
  "deadlineTime",
  "durationHours",
  "durationMinutes",
] as const;

export type TaskFormField = (typeof TASK_FORM_FIELDS)[number];
export type TaskFormValues = Record<TaskFormField, string>;

// Empty text means "not set".
const optional = (check: (value: string) => boolean, message: string) =>
  z
    .string()
    .trim()
    .refine((value) => value === "" || check(value), message)
    .transform((value) => value || null);

const wholeNumber = (max: number, message: string) =>
  z
    .string()
    .trim()
    .refine((value) => value === "" || (/^\d+$/.test(value) && Number(value) <= max), message)
    .transform((value) => (value === "" ? null : Number(value)));

const taskFormSchema = z
  .object({
    title: z.string().trim().min(1, "Please enter a title.").max(200, "The title can be at most 200 characters."),
    description: z
      .string()
      .trim()
      .max(5000, "The description can be at most 5000 characters.")
      .transform((value) => value || null),
    importance: z.enum(IMPORTANCE_LEVELS, { error: "Please choose High, Normal or Low." }),
    plannedDate: optional(isValidLocalDate, "Please enter a valid planned date."),
    plannedTime: optional(isValidLocalTime, "Please enter a valid time, for example 14:30."),
    deadlineDate: optional(isValidLocalDate, "Please enter a valid deadline date."),
    deadlineTime: optional(isValidLocalTime, "Please enter a valid time, for example 14:30."),
    durationHours: wholeNumber(168, "Hours must be a whole number from 0 to 168."),
    durationMinutes: wholeNumber(59, "Minutes must be a whole number from 0 to 59."),
  })
  .superRefine((data, ctx) => {
    if (data.plannedTime && !data.plannedDate) {
      ctx.addIssue({ code: "custom", path: ["plannedTime"], message: "Please choose a planned date for this time." });
    }
    if (data.deadlineTime && !data.deadlineDate) {
      ctx.addIssue({ code: "custom", path: ["deadlineTime"], message: "Please choose a deadline date for this time." });
    }
    const total = (data.durationHours ?? 0) * 60 + (data.durationMinutes ?? 0);
    if (total > MAX_ESTIMATED_MINUTES) {
      ctx.addIssue({ code: "custom", path: ["durationHours"], message: "The estimate can be at most 168 hours." });
    }
  })
  .transform(({ durationHours, durationMinutes, ...task }) => {
    const total = (durationHours ?? 0) * 60 + (durationMinutes ?? 0);
    return { ...task, estimatedMinutes: total > 0 ? total : null };
  });

export type TaskInput = z.output<typeof taskFormSchema>;

export type TaskFormResult =
  | { success: true; data: TaskInput }
  | { success: false; errors: Partial<Record<TaskFormField, string>>; values: TaskFormValues };

// Reads and validates the task form on the server. Unknown fields (such as a
// userId sent by a tampered browser) are ignored.
export function parseTaskForm(formData: FormData): TaskFormResult {
  const values = Object.fromEntries(
    TASK_FORM_FIELDS.map((field) => {
      const value = formData.get(field);
      return [field, typeof value === "string" ? value : ""];
    }),
  ) as TaskFormValues;

  const result = taskFormSchema.safeParse(values);
  if (result.success) return { success: true, data: result.data };

  const errors: Partial<Record<TaskFormField, string>> = {};
  for (const issue of result.error.issues) {
    const field = issue.path[0] as TaskFormField;
    errors[field] ??= issue.message;
  }
  return { success: false, errors, values };
}

export const taskStatusSchema = z.enum(TASK_STATUSES);

// Task ids are generated by the database (cuid); anything else is rejected early.
export const taskIdSchema = z.string().regex(/^[a-z0-9]{20,40}$/);
