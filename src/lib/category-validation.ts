import { z } from "zod";

import { CATEGORY_COLORS, MAX_CATEGORY_NAME_LENGTH } from "@/lib/category-rules";

// Names are trimmed first, then must be 1-50 characters.
export const categoryNameSchema = z
  .string({ error: "Please enter a category name." })
  .trim()
  .min(1, "Please enter a category name.")
  .max(MAX_CATEGORY_NAME_LENGTH, `The name can be at most ${MAX_CATEGORY_NAME_LENGTH} characters.`);

// Only the fixed palette is accepted; anything else (such as a CSS value) is refused.
export const categoryColorSchema = z.enum(CATEGORY_COLORS, { error: "Please choose a colour from the palette." });

// Category ids are generated by the database (cuid).
export const categoryIdSchema = z.string().regex(/^[a-z0-9]{20,40}$/);

export const categoryInputSchema = z.object({
  name: categoryNameSchema,
  // When no colour is sent, the server picks the next unused palette colour.
  color: categoryColorSchema.optional(),
});
